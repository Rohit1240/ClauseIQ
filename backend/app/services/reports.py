"""Downloadable extraction reports: standalone HTML (printable), CSV and JSON."""
from __future__ import annotations

import csv
import html
import io
import json

from clauseiq import config as ml_config


def to_json(analysis: dict, document: dict) -> str:
    return json.dumps({
        "analysis_id": analysis["id"], "created_at": analysis["created_at"],
        "document": {k: document[k] for k in ("filename", "file_type", "n_chars", "n_pages")},
        "models": analysis["models"], "categories": analysis["categories"],
        "runs": analysis["result"]["runs"], "clauses": analysis["result"]["clauses"],
        "comparison_summary": analysis["result"].get("comparison", {}).get("summary"),
    }, indent=2)


def to_csv(analysis: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["model", "category", "page_start", "page_end", "start_char", "end_char", "score",
                "threshold", "text"])
    for c in analysis["result"]["clauses"]:
        w.writerow([ml_config.MODEL_DISPLAY[c["model"]], c["category_name"], c["page_start"], c["page_end"],
                    c["start"], c["end"], c["score"], c["threshold"], c["text"]])
    return buf.getvalue()


def to_html(analysis: dict, document: dict) -> str:
    e = html.escape
    res = analysis["result"]
    rows = []
    by_cat: dict[str, list[dict]] = {}
    for c in res["clauses"]:
        by_cat.setdefault(c["category_name"], []).append(c)
    for cat in sorted(by_cat):
        rows.append(f"<h2>{e(cat)}</h2>")
        for c in by_cat[cat]:
            page = f"p. {c['page_start']}" + (f"–{c['page_end']}" if c["page_end"] != c["page_start"] else "")
            rows.append(
                f"<div class='clause'><div class='meta'><b>{e(ml_config.MODEL_DISPLAY[c['model']])}</b>"
                f" · {page} · chars {c['start']:,}–{c['end']:,} · score {c['score']:.2f}"
                f" (threshold {c['threshold']:.2f})</div><blockquote>{e(c['text'])}</blockquote></div>")
    runs = "".join(f"<li>{e(r['display_name'])}: {r['n_clauses']} spans in {r['seconds']:.2f}s</li>"
                   for r in res["runs"].values())
    comp = res.get("comparison", {}).get("summary") or {}
    return f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<title>ClauseIQ report — {e(document['filename'])}</title>
<style>
body{{font:14px/1.55 -apple-system,'Segoe UI',Inter,Arial,sans-serif;color:#1b1d21;max-width:860px;margin:40px auto;padding:0 24px}}
h1{{font:600 22px Georgia,serif;margin:0 0 4px}} h2{{font-size:15px;margin:28px 0 8px;border-bottom:1px solid #e3e1dc;padding-bottom:4px}}
.sub{{color:#5c6068}} .clause{{margin:10px 0 14px}} .meta{{color:#5c6068;font-size:12px;margin-bottom:4px}}
blockquote{{margin:0;padding:8px 12px;background:#faf9f6;border-left:3px solid #2a5bd7;white-space:pre-wrap}}
.note{{font-size:12px;color:#5c6068;border:1px solid #e3e1dc;padding:10px 12px;border-radius:6px;margin-top:16px}}
</style></head><body>
<h1>Clause extraction report</h1>
<div class="sub">{e(document['filename'])} · {document['n_pages']} page(s) · {document['n_chars']:,} characters · analysed {e(analysis['created_at'])}</div>
<ul>{runs}</ul>
<p class="sub">Cross-model findings: {comp.get('findings', 0)} ({comp.get('unanimous', 0)} found by every selected model).</p>
<div class="note">Generated by ClauseIQ. Predictions come from models trained from scratch on CUAD v1
(CC BY 4.0, The Atticus Project). Scores are model probabilities against validation-tuned thresholds,
not calibrated likelihoods. This is not legal advice; review every clause against the source document.</div>
{''.join(rows) or '<p>No clauses were extracted.</p>'}
</body></html>"""
